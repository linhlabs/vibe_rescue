#!/usr/bin/env python3
"""build_llms_full.py - write llms-full.txt: the key English documents in one file for LLM agents.

Sources: README.md, docs/V0.8_PREVIEW.md, and the English block of SECURITY.md.
Run it again after those files change:  python scripts/build_llms_full.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def english_block(security):
    marker = "## English"
    return security[security.index(marker):] if marker in security else security


def build():
    def read(rel):
        return (ROOT / rel).read_text(encoding="utf-8").strip()

    header = (
        "# Vibe Rescue: full text for LLMs\n\n> Generated by scripts/build_llms_full.py from README.md, "
        "docs/V0.8_PREVIEW.md and SECURITY.md (English block). Short index: llms.txt. "
        "Author and maintainer: Nguyễn Anh Nguyên (Nguyen Anh Nguyen). License: MIT."
    )
    parts = [
        header,
        "---\n\n# README.md\n\n" + read("README.md"),
        "---\n\n# docs/V0.8_PREVIEW.md\n\n" + read("docs/V0.8_PREVIEW.md"),
        "---\n\n# SECURITY.md (English)\n\n" + english_block(read("SECURITY.md")),
    ]
    return "\n\n".join(parts) + "\n"


def main():
    out = ROOT / "llms-full.txt"
    out.write_text(build(), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
